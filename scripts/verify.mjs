// Runs every headless scenario through the real CLI, checks expectations, checks determinism,
// and writes the evidence to docs/proof/<phase>/ (deterministic content -> CI can diff it).
// Usage: node scripts/verify.mjs [phase-N]   (default phase-1)
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { arch, cpus, platform, release, tmpdir } from 'node:os';
import { join } from 'node:path';
import { checkScenario, listScenarios, ROOT, runCli } from './scenario-lib.mjs';

const phase = process.argv[2] ?? 'phase-1';
const outDir = join(ROOT, 'docs', 'proof', phase);
const runsDir = join(outDir, 'runs');
rmSync(runsDir, { recursive: true, force: true });
mkdirSync(runsDir, { recursive: true });

const b = spawnSync('npm', ['run', 'build:headless', '--silent'], { cwd: ROOT, shell: true, encoding: 'utf8' });
if (b.status !== 0) {
  console.error(b.stderr);
  process.exit(1);
}

const rows = [];
let failed = 0;
for (const name of listScenarios()) {
  const { fails, exp } = checkScenario(name, runsDir);
  if (fails.length) failed++;
  rows.push(`| \`${name}\` | ${exp.note.replace(/\|/g, '\\|')} | ${fails.length ? 'FAIL: ' + fails.join('; ').replace(/\|/g, '\\|') : 'PASS'} |`);
  console.log(`${fails.length ? 'FAIL' : 'PASS'} ${name}${fails.length ? '\n  ' + fails.join('\n  ') : ''}`);
}

// Determinism: default level (random motes + shades), with inputs, run twice per seed.
const detInputs = join(tmpdir(), 'ddl-det-inputs.json');
writeFileSync(
  detInputs,
  JSON.stringify({
    frames: [
      { tick: 0, move: [0.3, 1], cam_yaw_deg: 15 },
      { tick: 400, move: [-1, 0], pulse: true },
      { tick: 401, pulse: false },
      { tick: 900, move: [0, -1], cam_yaw_deg: 200, jump: true },
      { tick: 901, jump: false },
    ],
  }),
);
const detRows = [];
for (const seed of [1, 42, 20261120]) {
  const h = [0, 1].map((i) => {
    const r = runCli({ seed, ticks: 3600, inputs: detInputs, outFile: join(tmpdir(), `ddl-det-${seed}-${i}.jsonl`) });
    return createHash('sha256').update(r.text).digest('hex').slice(0, 16);
  });
  const ok = h[0] === h[1];
  if (!ok) failed++;
  detRows.push(`| ${seed} | 3600 | \`${h[0]}\` | \`${h[1]}\` | ${ok ? 'PASS' : 'FAIL'} |`);
  console.log(`${ok ? 'PASS' : 'FAIL'} determinism seed ${seed}`);
}

const report = `# Verify report — ${phase}

Generated by \`npm run verify -- ${phase}\` (scripts/verify.mjs). Every row is produced by running the real
headless CLI \`node build/headless.mjs\`; raw outputs are in [runs/](runs/). Expectations live in
\`tests/scenarios/<name>/expect.json\` and were computed by hand from the rules, not copied from output.

## Scenarios

| Scenario | What it proves | Result |
|---|---|---|
${rows.join('\n')}

## Determinism (same seed + same inputs, two runs, default level with random spawns)

| Seed | Ticks | sha256 run 1 | sha256 run 2 | Result |
|---|---|---|---|---|
${detRows.join('\n')}

**Total: ${failed === 0 ? 'ALL PASS' : failed + ' FAILED'}**
`;
writeFileSync(join(outDir, 'verify-report.md'), report);
writeFileSync(
  join(outDir, 'env.txt'),
  `node ${process.version}\n${platform()} ${release()} ${arch()}\n${cpus()[0]?.model ?? ''}\n`,
);
console.log(`\nreport: docs/proof/${phase}/verify-report.md`);
process.exit(failed ? 1 : 0);
