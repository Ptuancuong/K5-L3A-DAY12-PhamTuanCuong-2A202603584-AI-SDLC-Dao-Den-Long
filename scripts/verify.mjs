// Runs every headless scenario through the real CLI, checks expectations, checks determinism,
// and writes the evidence to docs/proof/<phase>/ (deterministic content -> CI can diff it).
// Usage: node scripts/verify.mjs [phase-N]   (default phase-1)
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { arch, cpus, platform, release, tmpdir } from 'node:os';
import { join } from 'node:path';
import { checkScenario, listScenarios, ROOT, runCli } from './scenario-lib.mjs';

const phase = process.argv[2] ?? 'phase-1';
const outDir = join(ROOT, 'docs', 'proof', phase);
const runsDir = join(outDir, 'runs');
rmSync(runsDir, { recursive: true, force: true });
mkdirSync(runsDir, { recursive: true });

const b = spawnSync('npm', ['run', 'build:headless', '--silent'], { cwd: ROOT, shell: true, encoding: 'utf8' });
if (b.status !== 0) {
  console.error(b.stderr);
  process.exit(1);
}

const rows = [];
let failed = 0;
for (const name of listScenarios()) {
  const { fails, exp } = checkScenario(name, runsDir);
  if (fails.length) failed++;
  rows.push(`| \`${name}\` | ${exp.note.replace(/\|/g, '\\|')} | ${fails.length ? 'FAIL: ' + fails.join('; ').replace(/\|/g, '\\|') : 'PASS'} |`);
  console.log(`${fails.length ? 'FAIL' : 'PASS'} ${name}${fails.length ? '\n  ' + fails.join('\n  ') : ''}`);
}

// Determinism: default level (random motes + shades), with inputs, run twice per seed.
const detInputs = join(tmpdir(), 'ddl-det-inputs.json');
writeFileSync(
  detInputs,
  JSON.stringify({
    frames: [
      { tick: 0, move: [0.3, 1], cam_yaw_deg: 15 },
      { tick: 400, move: [-1, 0], pulse: true },
      { tick: 401, pulse: false },
      { tick: 900, move: [0, -1], cam_yaw_deg: 200, jump: true, dash: true },
      { tick: 901, jump: false, dash: false },
      { tick: 1500, pause: true }, { tick: 1501, pause: false }, { tick: 1600, pause: true },
    ],
  }),
);
const detRows = [];
for (const [seed, night] of [[1, 1], [42, 2], [20261120, 3]]) {
  const h = [0, 1].map((i) => {
    const r = runCli({ seed, night, ticks: 3600, inputs: detInputs, outFile: join(tmpdir(), `ddl-det-${seed}-${i}.jsonl`) });
    return createHash('sha256').update(r.text).digest('hex').slice(0, 16);
  });
  const ok = h[0] === h[1];
  if (!ok) failed++;
  detRows.push(`| ${seed} (Đêm ${night}) | 3600 | \`${h[0]}\` | \`${h[1]}\` | ${ok ? 'PASS' : 'FAIL'} |`);
  console.log(`${ok ? 'PASS' : 'FAIL'} determinism seed ${seed}`);
}

// Ticket-04 (phase-4+): run the contract's soak_cmd, check the committed bench.json thresholds.
// Only PASS/FAIL goes into the report (numbers depend on the machine; they are in soak.json / bench.json).
const p4Rows = [];
if (Number(phase.split('-')[1]) >= 4) {
  const contract = JSON.parse(readFileSync(join(ROOT, 'game.contract.json'), 'utf8'));
  const check = (what, ok) => {
    if (!ok) failed++;
    if (!ok && process.env.GITHUB_ACTIONS) console.log(`::error title=verify::FAIL ${what}`);
    p4Rows.push(`| ${what} | ${ok ? 'PASS' : 'FAIL'} |`);
    console.log(`${ok ? 'PASS' : 'FAIL'} ${what}`);
  };
  const soakOut = join(tmpdir(), 'ddl-soak.json');
  const s = spawnSync(`${contract.soak_cmd} --seed 7 --nights 10 --out "${soakOut}"`, { cwd: ROOT, shell: true, encoding: 'utf8' });
  let soak = null;
  try {
    soak = JSON.parse(readFileSync(soakOut, 'utf8'));
  } catch {
    /* reported below */
  }
  if (process.env.GITHUB_ACTIONS) {
    // CI logs need a login; annotations are public, so surface the soak numbers there.
    const brief = soak ? `mem ${soak.mem_start_mb} -> ${soak.mem_end_mb} MB, crashes ${soak.crashes}, ${soak.duration_s} s, ${soak.node}` : `no soak.json; exit ${s.status}; ${String(s.stderr).slice(0, 300)}`;
    console.log(`::notice title=soak ${platform()} ${arch()}::${brief}`);
  }
  check('soak_cmd --seed 7 --nights 10: exit 0, 10 results won/lost', s.status === 0 && soak?.nights === 10 && soak.results.length === 10 && soak.results.every((r) => r === 'won' || r === 'lost'));
  check('soak: crashes = 0', soak?.crashes === 0);
  check('soak: mem_end_mb <= 1.2 x mem_start_mb', soak !== null && soak.mem_end_mb <= 1.2 * soak.mem_start_mb);
  const bench = JSON.parse(readFileSync(join(ROOT, 'bench.json'), 'utf8'));
  const keys = ['contract_version', 'avg_fps', 'p1_low_fps', 'frame_ms_p95', 'frames', 'load_ms', 'peak_mem_mb', 'vsync_off', 'renderer', 'os'];
  check('bench.json (committed) has every contract field, contract_version 1.3', keys.every((k) => k in bench) && bench.contract_version === '1.3');
  check('bench.json: avg_fps >= 60, p1_low_fps >= 30, load_ms <= 10000 (on the machine in bench.json.os)', bench.avg_fps >= 60 && bench.p1_low_fps >= 30 && bench.load_ms <= 10000);
}

const report = `# Verify report — ${phase}

Generated by \`npm run verify -- ${phase}\` (scripts/verify.mjs). Every row is produced by running the real
headless CLI \`node build/headless.mjs\`; raw outputs are in [runs/](runs/). Expectations live in
\`tests/scenarios/<name>/expect.json\` and were computed by hand from the rules, not copied from output.

## Scenarios

| Scenario | What it proves | Result |
|---|---|---|
${rows.join('\n')}

## Determinism (same seed + same inputs, two runs, default level with random spawns)

| Seed | Ticks | sha256 run 1 | sha256 run 2 | Result |
|---|---|---|---|---|
${detRows.join('\n')}

${p4Rows.length ? `## Ticket-04: soak (run now) and bench (committed bench.json)\n\n| Check | Result |\n|---|---|\n${p4Rows.join('\n')}\n\n` : ''}**Total: ${failed === 0 ? 'ALL PASS' : failed + ' FAILED'}**
`;
writeFileSync(join(outDir, 'verify-report.md'), report);
writeFileSync(
  join(outDir, 'env.txt'),
  `node ${process.version}\n${platform()} ${release()} ${arch()}\n${cpus()[0]?.model ?? ''}\n`,
);
console.log(`\nreport: docs/proof/${phase}/verify-report.md`);
process.exit(failed ? 1 : 0);
